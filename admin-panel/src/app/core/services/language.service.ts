@Injectable({ providedIn: 'root' })
export class LanguageService {
  readonly lang = signal<Lang>((localStorage.getItem('lang') as Lang) || 'tr');

  setLang(l: Lang): void {
    this.lang.set(l);
    localStorage.setItem('lang', l);
  }

  t(key: string): string {
    return T[this.lang()][key] ?? key;
  }

  get dateLocale(): string {
    return { tr: 'tr-TR', en: 'en-US', ru: 'ru-RU', de: 'de-DE' }[this.lang()];
  }

  get langLabel(): string {
    return { tr: 'TR', en: 'EN', ru: 'RU', de: 'DE' }[this.lang()];
  }
}
